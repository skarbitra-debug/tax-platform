/**
 * Единый нормализатор российского телефона (контракт §1): канон "+7XXXXXXXXXX".
 * Используется и анкетой клиента (leadFormSchema), и регистрацией риэлтора.
 *
 * Принимает житейские варианты ввода: "8 (926) 123-45-67", "+7 926 123 45 67",
 * "79261234567" — оформление (скобки/пробелы/дефисы) вычищается, префикс
 * 8/7/+7 приводится к "+7". Всё, что не похоже на номер РФ (иностранные коды,
 * буквы, неверная длина, 10 цифр без префикса), — null: звонить по такому
 * номеру девочкам-исполнительницам бесполезно (§4.5 ТЗ).
 */
export function normalizeRuPhone(raw: string): string | null {
  // Вычищаем только оформление; любой другой мусор (буквы, точки) валит regex ниже
  const cleaned = raw.trim().replace(/[\s()-]/g, "");
  const match = /^(?:\+7|7|8)(\d{10})$/.exec(cleaned);
  return match ? `+7${match[1]}` : null;
}
