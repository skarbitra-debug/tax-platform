/**
 * Тесты normalizeRuPhone (M1-1): 8/7/+7 + скобки/пробелы/дефисы → канон
 * "+7XXXXXXXXXX"; мусор и иностранные номера → null. Чистая функция, без БД.
 */
import { describe, expect, it } from "vitest";
import { normalizeRuPhone } from "./phone";

const CANON = "+79261234567";

describe("normalizeRuPhone — валидные варианты ввода", () => {
  it.each([
    ["89261234567", "голое 8…"],
    ["79261234567", "голое 7…"],
    ["+79261234567", "уже канон +7…"],
    ["8 (926) 123-45-67", "8 со скобками и дефисами"],
    ["+7 (926) 123-45-67", "+7 со скобками и дефисами"],
    ["7 926 123 45 67", "7 с пробелами"],
    ["8-926-123-45-67", "8 с дефисами"],
    ["  +79261234567  ", "внешние пробелы"],
  ])("%s → +79261234567 (%s)", (raw) => {
    expect(normalizeRuPhone(raw)).toBe(CANON);
  });
});

describe("normalizeRuPhone — мусор и не-РФ → null", () => {
  it.each([
    ["", "пустая строка"],
    ["привет", "буквы"],
    ["8926123456", "10 цифр с 8 — короткий"],
    ["892612345678", "12 цифр с 8 — длинный"],
    ["9261234567", "10 цифр без префикса 8/7/+7"],
    ["+380501234567", "Украина"],
    ["+15551234567", "США"],
    ["+79261234a67", "буква внутри"],
    ["8.926.123.45.67", "точки не являются оформлением"],
    ["++79261234567", "двойной плюс"],
  ])("%s → null (%s)", (raw) => {
    expect(normalizeRuPhone(raw)).toBeNull();
  });
});
